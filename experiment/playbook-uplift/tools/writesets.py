#!/usr/bin/env python3
"""Write-set obligations for the worked example (playbook §3.3a step 5).

    python experiment/playbook-uplift/tools/writesets.py           # check and write semantics/WRITESETS.md
    python experiment/playbook-uplift/tools/writesets.py --check   # also fail if WRITESETS.md is stale

Reads semantics/writesets.json. For every invariant and every plan whose writes meet the invariant's reads, a coverage
entry must exist; an entry for a pair that is not an obligation is stale. Each plan's code reference must exist at the
pin with its lines in range, and each finding, proof or live/mc id a coverage entry names must resolve (FINDINGS,
proofs/, evidence/runs.json). A pair whose coverage names a finding is reported as open: the obligation is known and
not met by the code at the pin.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ontology_index import PIN, REPO, UPLIFT, Tree, ids_in, proof_sources  # noqa: E402

SPEC = UPLIFT / "semantics" / "writesets.json"
OUT = UPLIFT / "semantics" / "WRITESETS.md"


def main() -> int:
    check = "--check" in sys.argv
    spec = json.loads(SPEC.read_text())
    tree = Tree(REPO, PIN)
    errors = []
    for name, plan in spec["plans"].items():
        m = re.match(r"^(.+?):(\d+)(?:-(\d+))?$", plan["code"])
        text = tree.text(m.group(1)) if m else None
        if text is None:
            errors.append(f"plan {name}: code {plan['code']} not at the pin")
            continue
        n = text.count("\n") + 1
        if not (1 <= int(m.group(2)) <= int(m.group(3) or m.group(2)) <= n):
            errors.append(f"plan {name}: lines outside {m.group(1)} (1-{n})")
        for st in plan["writes"]:
            if st not in spec["stores"]:
                errors.append(f"plan {name}: unknown store {st}")
    pairs = []
    for inv, d in spec["invariants"].items():
        for name, plan in spec["plans"].items():
            if set(d["reads"]) & set(plan["writes"]):
                pairs.append((inv, name))
    cov = spec["coverage"]
    want = {f"{i}|{p}" for i, p in pairs}
    for k in sorted(want - set(cov)):
        errors.append(f"uncovered obligation {k}")
    for k in sorted(set(cov) - want):
        errors.append(f"stale coverage {k} (the plan does not write what the invariant reads)")
    findings = ids_in(UPLIFT / "FINDINGS.md", "F")
    proofs = "\n".join(p.read_text() for p in proof_sources(UPLIFT) if p.suffix == ".rs")
    runs = json.loads((UPLIFT / "evidence" / "runs.json").read_text()).get("runs", {})
    for k, v in cov.items():
        for f in re.findall(r"finding:(F-\d+)", v):
            if f not in findings:
                errors.append(f"{k}: {f} not in FINDINGS.md or findings/")
        for f in re.findall(r"proved:(\w+)", v):
            if not re.search(rf"\bproof\s+fn\s+{f}\b", proofs):
                errors.append(f"{k}: proved:{f} is not a proof fn")
        for kind, rid in re.findall(r"\b(live|mc):([\w-]+)", v):
            if runs.get(rid, {}).get("result") != "pass":
                errors.append(f"{k}: {kind}:{rid} not a passing registry entry")
    rows, open_n = [], 0
    for inv, name in pairs:
        v = cov.get(f"{inv}|{name}", "")
        status = "open (finding)" if re.search(r"finding:", v) and not re.search(r"proved:|guard:|mc:", v) else "discharged"
        if "finding:" in v and status == "discharged":
            status = "discharged for the reviewed design; finding at the pin"
        open_n += status.startswith("open")
        rows.append(f"| {inv} | {name} | {status} | {v.replace('|', '/')} |")
    text = ["# Write-set obligations (generated)", "",
            "Generated by `tools/writesets.py` from `semantics/writesets.json`. Do not edit.", "",
            f"{len(spec['invariants'])} invariants, {len(spec['plans'])} write plans, {len(pairs)} obligations "
            f"(every plan that writes what an invariant reads), {open_n} open.", "",
            "| Invariant | Plan | Status | Discharged by |", "|---|---|---|---|"] + rows
    if errors:
        text += ["", "## Errors", ""] + [f"- {e}" for e in errors]
    body = "\n".join(text) + "\n"
    if check:
        stale = not OUT.exists() or OUT.read_text() != body
        for e in errors:
            print("WRITESETS:", e)
        print(f"{len(pairs)} obligations, {open_n} open, {len(errors)} error(s){', WRITESETS.md stale' if stale else ''}")
        return 1 if errors or stale else 0
    OUT.write_text(body)
    for e in errors:
        print("WRITESETS:", e)
    print(f"{len(pairs)} obligations, {open_n} open, {len(errors)} error(s); wrote {OUT.relative_to(REPO)}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
