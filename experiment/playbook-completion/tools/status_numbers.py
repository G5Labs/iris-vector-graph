#!/usr/bin/env python3
"""The numbers STATUS.md quotes, computed from the committed artifacts (review R4-13: the account lagged the lanes).

    python tools/status_numbers.py            # print the generated block
    python tools/status_numbers.py --write    # replace the block between the markers in STATUS.md
    python tools/status_numbers.py --check    # exit 1 if STATUS.md's block differs from the generated one
    python tools/status_numbers.py --self-test

Sources: findings/audit/*.json (last record per id wins, as the matrix reads them; duplicates are not counted),
every proofs*/RESULTS.json (baseline verified/errors, number of controls), every models/*/RESULTS.json (number of
checks), matrix/obligations.json (status and product counts). Nothing here is hand-typed.
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- numbers:begin (generated by tools/status_numbers.py; do not edit) -->", "<!-- numbers:end -->"


def findings(root: Path) -> dict:
    recs = {}
    for p in sorted((root / "findings" / "audit").glob("*.json")):
        d = json.loads(p.read_text())
        for r in (d if isinstance(d, list) else d.get("findings", []) + d.get("new_findings", [])):
            recs[r["id"]] = r
    orig = {k: v for k, v in recs.items() if not k.startswith("F-C")}
    new = {k: v for k, v in recs.items() if k.startswith("F-C") and v.get("disposition") != "duplicate"}
    dup = sorted(k for k, v in recs.items() if v.get("disposition") == "duplicate")
    rep = ("reproduced-live", "reproduced-test", "reproduced-model", "confirmed-source")
    s1 = sorted(k for k, v in recs.items() if v.get("severity") == "S1" and v.get("disposition") in rep)
    return {"original": len(orig), "original_by_disposition": dict(sorted(collections.Counter(
                v.get("disposition") for v in orig.values()).items())),
            "new": len(new), "new_by_disposition": dict(sorted(collections.Counter(
                v.get("disposition") for v in new.values()).items())),
            "new_by_severity": dict(sorted(collections.Counter(v.get("severity") for v in new.values()).items())),
            "duplicates": dup, "s1_reproduced": s1}


def proofs(root: Path) -> list:
    out = []
    for p in sorted(root.glob("proofs*/RESULTS.json")):
        d = json.loads(p.read_text())
        b = d.get("baseline") or {}
        out.append({"crate": p.parent.name, "verified": b.get("verified"), "errors": b.get("errors"),
                    "controls": len(d.get("controls") or {})})
    return out


def models(root: Path) -> list:
    out = []
    for p in sorted((root / "models").glob("*/RESULTS.json")):
        d = json.loads(p.read_text())
        r = d if isinstance(d, list) else (d.get("checks") or d.get("results") or [])
        out.append({"crate": p.parent.name, "checks": len(r) if isinstance(r, (list, dict)) else None})
    return out


def block(root: Path) -> str:
    f, pr, mo = findings(root), proofs(root), models(root)
    ob = json.loads((root / "matrix" / "obligations.json").read_text())
    lines = [BEGIN, "", "| Quantity | Value |", "|---|---|"]
    lines.append(f"| Original findings (submission 9c3719c1) | {f['original']}: " +
                 ", ".join(f"{k} {v}" for k, v in f["original_by_disposition"].items()) + " |")
    lines.append(f"| New findings (F-C*, duplicates excluded) | {f['new']}: " +
                 ", ".join(f"{k} {v}" for k, v in f["new_by_disposition"].items()) + "; " +
                 ", ".join(f"{k} {v}" for k, v in f["new_by_severity"].items()) + " |")
    if f["duplicates"]:
        lines.append(f"| Duplicate finding records (merged into another id) | {', '.join(f['duplicates'])} |")
    lines.append(f"| Reproduced or source-confirmed S1 findings | {len(f['s1_reproduced'])}: {', '.join(f['s1_reproduced'])} |")
    tv = sum(p["verified"] or 0 for p in pr)
    lines.append(f"| Verus crates (baseline verified / errors / controls) | {len(pr)} crates, {tv} verified in total: " +
                 "; ".join(f"`{p['crate']}` {p['verified']}/{p['errors']}/{p['controls']}" for p in pr) + " |")
    lines.append("| Explorer crates (checks in RESULTS.json) | " +
                 "; ".join(f"`{m['crate']}` {m['checks']}" for m in mo) + " |")
    ws = json.loads((root / "writesets" / "DISCHARGES.json").read_text()) if (root / "writesets" / "DISCHARGES.json").exists() else {}
    ba = json.loads((root / "writesets" / "BREADTH-A-DISCHARGES.json").read_text()) if (root / "writesets" / "BREADTH-A-DISCHARGES.json").exists() else {}
    if ws or ba:
        cen = collections.Counter(v.get("discharge") for k, v in ws.items() if not k.startswith(("_", "module:")))
        bac = collections.Counter(v.get("discharge") for k, v in ba.items() if not k.startswith("_"))
        lines.append("| Write-set discharges (census obligations; breadth-a module-invariant pairs) | census " +
                     f"{sum(cen.values())}: " + ", ".join(f"{k} {v}" for k, v in sorted(cen.items())) + "; breadth-a " +
                     f"{sum(bac.values())}: " + ", ".join(f"{k} {v}" for k, v in sorted(bac.items())) + " |")
    cov = root / "contract-2" / "coverage.json"
    if cov.exists():
        mods = json.loads(cov.read_text())["modules"]
        tot = collections.Counter()
        for m in mods.values():
            tot.update(m.get("counts", {}))
        lines.append(f"| IRIS features used by the product's code, all {len(mods)} modules (contract-2) | " +
                     ", ".join(f"{k} {tot[k]}" for k in ("inside", "validated", "outside", "unclassified")) + " |")
    lines.append("| Matrix cells by status | " + ", ".join(f"{k} {v}" for k, v in sorted(ob["status_counts"].items())) + " |")
    lines.append("| Matrix cells by product obligation | " +
                 ", ".join(f"{k} {v}" for k, v in sorted(ob["product_counts"].items())) + " |")
    lines += ["", END]
    return "\n".join(lines)


def current(status: str) -> str | None:
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), status, re.S)
    return m.group(0) if m else None


def self_test() -> int:
    import shutil
    import tempfile
    ok = True
    with tempfile.TemporaryDirectory() as t:
        r = Path(t) / "c"
        for sub in ("findings", "matrix"):
            shutil.copytree(ROOT / sub, r / sub)
        for p in ROOT.glob("proofs*/RESULTS.json"):
            (r / p.parent.name).mkdir(parents=True, exist_ok=True)
            shutil.copy(p, r / p.parent.name / "RESULTS.json")
        for p in (ROOT / "models").glob("*/RESULTS.json"):
            (r / "models" / p.parent.name).mkdir(parents=True, exist_ok=True)
            shutil.copy(p, r / "models" / p.parent.name / "RESULTS.json")
        base = block(r)
        # a new S1 finding must change the block
        p = r / "findings" / "audit" / "zz-selftest.json"
        p.write_text(json.dumps([{"id": "F-C9999", "disposition": "reproduced-live", "severity": "S1"}]))
        ok &= block(r) != base and "F-C9999" in block(r)
        p.unlink()
        # a changed verified count must change the block
        q = next(r.glob("proofs*/RESULTS.json"))
        d = json.loads(q.read_text())
        d["baseline"]["verified"] = (d["baseline"].get("verified") or 0) + 1
        q.write_text(json.dumps(d))
        ok &= block(r) != base
    print("self-test", "pass" if ok else "FAIL")
    return 0 if ok else 1


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    b = block(ROOT)
    sp = ROOT / "STATUS.md"
    if "--write" in sys.argv:
        s = sp.read_text()
        cur = current(s)
        sp.write_text(s.replace(cur, b) if cur else s.rstrip("\n") + "\n\n## Numbers\n\n" + b + "\n")
        print("written")
        return 0
    if "--check" in sys.argv:
        cur = current(sp.read_text())
        ok = cur == b
        print("status numbers", "current" if ok else "STALE or missing")
        return 0 if ok else 1
    print(b)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
