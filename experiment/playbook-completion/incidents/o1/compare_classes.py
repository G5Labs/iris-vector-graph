#!/usr/bin/env python3
"""O-1 record: attribute every class exported (read-only, $System.OBJ.ExportUDL) from %SYS IVGDev.* and from namespace
IVG262FC1306 to the pin's sources, the unchanged v4.5.1 release (git tag v4.5.1, f60b20c2) or neither.

    python incidents/o1/compare_classes.py $RUN_DIR/o1/exported OUT.json

Normalization (both sides): trailing whitespace and blank lines removed; the deploy-time `Parameter SOURCEHASH` value
blanked; the schema names the pin's deploy rewrites under schema_prefix (Graph_KG, Graph.KG, RAG) mapped to one token.
Classes in neither tree are generated by IRIS from the deployed classes (SQL procedure/function wrappers, table
classes) or by the release's own setup; they are listed, not attributed.
"""
import hashlib, json, re, subprocess, sys, collections
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]


def norm(t: str) -> str:
    t = re.sub(r'Parameter SOURCEHASH = "[^"]*";', 'Parameter SOURCEHASH = "";', t.replace("\r\n", "\n"))
    t = re.sub(r"\b(Graph_KG|Graph\.KG|RAG)\b", "S", t)
    return "\n".join(l.rstrip() for l in t.split("\n") if l.strip())


def h(t: str) -> str:
    return hashlib.sha256(norm(t).encode()).hexdigest()


def tree(rev=None):
    out = {}
    if rev is None:
        for base in ("iris_src/src", "scripts/dev/objectscript"):
            for p in (REPO / base).rglob("*.cls"):
                out[p.relative_to(REPO / base).with_suffix("").as_posix().replace("/", ".")] = h(p.read_text(errors="replace"))
    else:
        names = subprocess.run(["git", "-C", str(REPO), "ls-tree", "-r", "--name-only", rev, "--", "iris_src/src"],
                               capture_output=True, text=True).stdout.split()
        for f in names:
            if f.endswith(".cls"):
                t = subprocess.run(["git", "-C", str(REPO), "show", f"{rev}:{f}"], capture_output=True, text=True).stdout
                out[Path(f).relative_to("iris_src/src").with_suffix("").as_posix().replace("/", ".")] = h(t)
    return out


def main():
    exp, out = Path(sys.argv[1]), Path(sys.argv[2])
    pin, rel = tree(), tree("v4.5.1")
    res = {"pin": "3eaa79cf77d3e0a879b2cced634cf2729d81499e", "release": "v4.5.1 f60b20c20de13bffb30c2fbb9cdb3a4e73f3a675"}
    for sub in ("SYS", "FC"):
        rows = []
        for p in sorted((exp / sub).glob("*.cls")):
            n, hi = p.stem, h(p.read_text(errors="replace"))
            rows.append({"class": n, "equals_pin": pin.get(n) == hi if n in pin else None,
                         "equals_v451": rel.get(n) == hi if n in rel else None})
        g = collections.defaultdict(list)
        for r in rows:
            k = ("pin" if r["equals_pin"] else "pin-name-other-text" if r["equals_pin"] is False else "no-pin-name") + "/" + \
                ("v451" if r["equals_v451"] else "v451-name-other-text" if r["equals_v451"] is False else "no-v451-name")
            g[k].append(r["class"])
        res[sub] = {"classes": rows, "groups": dict(g)}
        print(sub, len(rows), {k: len(v) for k, v in g.items()})
    out.write_text(json.dumps(res, indent=1))


if __name__ == "__main__":
    main()
