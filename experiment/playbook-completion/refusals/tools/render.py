#!/usr/bin/env python3
"""Render refusals/REFUSALS.md from refusals/audit.json (written by rx_audit.py) and merge the lane's finding
fragments (refusals/findings/*.json) into findings/audit/zz-refusals.json.

    python render.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parent
COMPLETION = LANE.parent

NAMES = {"01": "install and schema", "04": "adjacency", "06": "vectors", "10": "algorithms", "11": "ledger core",
         "15": "integrations", "16": "interfaces", "17": "operations", "18": "snapshot"}


def esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


PRIV_RUNS = [("r1", "rx-live-priv"), ("r2", "(not registered: harness error at its case c)"), ("r3", "rx-live-priv-vec")]


def priv_section() -> list:
    """The least-privilege windows (operator-authorised user IVGAUDIT_RO, versions/PRIVILEGE.md), from the logs."""
    import os
    rd = Path(os.environ.get("RUN_DIR", "/nonexistent")) / "refusals" / "priv"
    if not rd.is_dir():
        return []
    out = ["", "## Least-privilege probes (IVGAUDIT_RO in AUDITE)", "",
           "The disposable user `IVGAUDIT_RO` (role `IVGAUDIT_RO_ROLE`, versions/PRIVILEGE.md) was enabled only for "
           "each window below, given exactly the SQL privileges each scenario needs (GRANT as SQL in AUDITE, grantor "
           "`_SYSTEM`), and every grant was revoked with `REVOKE ... AS \"_SYSTEM\"` and confirmed by `CheckPrivilege` "
           "0 before the next scenario; role resource changes were made in `%SYS` and restored to the recorded value "
           "at once. The password reached the process only as the environment variable `IVGAUDIT_PW` "
           "(`refusals/priv/run_priv.sh`); a scan of every log finds it nowhere. Final state after each window: "
           "user Enabled 0 (login Access Denied), role resources as before, 0 SQL privileges in AUDITE, "
           "`CheckPrivilege` 0 on every Graph_KG table for s/i/u/d (`rx-live-priv-final`).", "",
           "| Window (UTC, 2026-11-14) | Run | Scenario | SQL grants in AUDITE (all revoked) | Role resources |",
           "|---|---|---|---|---|"]
    for tag, run in PRIV_RUNS:
        f = rd / f"results-{tag}.json"
        if not f.is_file():
            continue
        d = json.loads(f.read_text())
        ev = next(c for c in d["cases"] if c.get("case") == "events")["events"]
        en = next(e["utc"][11:19] for e in ev if e["event"] == "enable user")
        di = next(e["utc"][11:19] for e in ev if e["event"] == "disable user")
        scen, grants, roles = None, {}, {}
        for e in ev:
            if e["event"].startswith("scenario ") and e["event"].endswith(" start"):
                scen = e["event"][9:-6]
            elif e["event"] == "grant" and scen:
                st = e["statement"].replace("GRANT ", "").replace(" TO IVGAUDIT_RO_ROLE", "")
                grants.setdefault(scen, []).append(st)
            elif e["event"].startswith("role resources (") and "final" not in e["event"] and scen:
                roles.setdefault(scen, []).append(e["result"].split("<<ROLE:")[-1].split(":ROLE>>")[0])
        for sc in grants:
            g = grants[sc]
            sel = [x for x in g if x.startswith("SELECT ON Graph_KG.")]
            other = [x for x in g if not x.startswith("SELECT ON Graph_KG.")]
            gtxt = "; ".join(other + ([f"SELECT on {len(sel)} tables ({', '.join(x[19:] for x in sel)})"] if sel else []))
            out.append(f"| {en}-{di} | {run} | {sc} | {gtxt} | {'; then '.join(roles.get(sc, [])) or 'unchanged (%DB_%DEFAULT:R, %Native_ClassExecution:U, %Native_GlobalAccess:U)'} |")
    return out


def main() -> int:
    a = json.loads((LANE / "audit.json").read_text())
    xs = {s["id"]: s for s in json.loads((LANE / "x-statements.json").read_text())["statements"]}
    by_mod = {}
    for e in a["statements"]:
        by_mod.setdefault(xs[e["id"]]["module"], []).append(e)
    out = ["# Stated refusals audited mechanically (gate 5c-refusals)", "",
           "Generated by `refusals/tools/render.py` from `refusals/audit.json` (checked by `refusals/tools/rx_audit.py`,"
           " run `rx-audit-r2`; extraction `refusals/tools/extract_x.py`, self-tests `rx-audit-selftest-r2`). Product pin "
           "`3eaa79cf`. Namespace AUDITE. Every X statement of the nine modules is listed once. Outcomes:"
           " **holds-live** = triggered through the product's real entry point, refused as stated, and the IRIS journal"
           " (traces/journal.py, all processes, AUDITE's database) shows no net change outside the stores the"
           " statement names; **product-defect** = accepted, changed something, or refused differently (finding);"
           " **blocked-access** = the trigger needs an unavailable dependency (named); **holds-run** = shown by an"
           " upstream test in a registered run (substring checked in its log); **holds-inspected** = no entry point"
           " here can trigger the condition (reason given).", "",
           f"Audited {a['audited']}/{a['expected']}; check errors: {len(a['errors'])}.", "",
           "| Module | " + " | ".join(sorted({o for m in a['per_module'].values() for o in m})) + " | total |",
           "|---|" + "---:|" * (len({o for m in a['per_module'].values() for o in m}) + 1)]
    outs = sorted({o for m in a["per_module"].values() for o in m})
    for m in sorted(a["per_module"]):
        row = a["per_module"][m]
        out.append(f"| {m} {NAMES.get(m, '')} | " + " | ".join(str(row.get(o, 0)) for o in outs)
                   + f" | {sum(row.values())} |")
    for m in sorted(by_mod):
        out += ["", f"## Module {m} ({NAMES.get(m, '')})", "",
                "| X statement | Text | Implementing code (pin) | Evidence | Outcome | Notes |", "|---|---|---|---|---|---|"]
        for e in by_mod[m]:
            ev = ", ".join(x.replace("run:", "") for x in e.get("evidence", []))
            if e.get("live_cases"):
                ev += f" ({len(e['live_cases'])} case{'s' if len(e['live_cases']) != 1 else ''})"
            oc = e["outcome"]
            if e.get("finding"):
                oc += f" ({e['finding']})"
            if e.get("dependency"):
                oc += f": {e['dependency']}"
            code = "; ".join(e.get("implementing_code") or []) or ("absent: " + e.get("absent", ""))
            out.append(f"| {e['id']} | {esc(e['text'])} | {esc(code)} | {esc(ev)} | {esc(oc)} | {esc(e.get('notes', ''))} |")
    out += priv_section()
    (LANE / "REFUSALS.md").write_text("\n".join(out) + "\n")
    # findings
    merged = []
    for f in sorted((LANE / "findings").glob("*.json")):
        merged += json.loads(f.read_text())
    ids = [x["id"] for x in merged]
    assert len(ids) == len(set(ids)), f"duplicate finding ids {ids}"
    (COMPLETION / "findings" / "audit" / "zz-refusals.json").write_text(json.dumps(merged, indent=1) + "\n")
    print(f"REFUSALS.md: {len(a['statements'])} statements; zz-refusals.json: {len(merged)} findings {ids}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
