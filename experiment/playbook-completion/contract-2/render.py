#!/usr/bin/env python3
"""Render contract-2/COVERAGE-2.md (per-module tables) and contract-2/MATRIX-INPUT.json from coverage.json,
VALIDATED.json and the run registry. The narrative sections are COVERAGE-2.head.md (hand-written)."""
import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PC = HERE.parent
cov = json.loads((HERE / "coverage.json").read_text())
val = json.loads((HERE / "VALIDATED.json").read_text())
obl = json.loads((PC / "matrix" / "obligations.json").read_text())
OPEN = ["01", "02", "03", "04", "05", "06", "07", "08", "09", "10", "11", "15", "16", "17", "18"]
CLOSED = ["12", "13", "14"]
CLAUSE_RUNS = {c: v["runs"] for c, v in val["clauses"].items()}
NEW_FINDINGS = {"17": ["F-C1720"]}
EXTRA_EV = {"17": ["run:env2-fc1720-query-nodes", "run:env2-fc1720-query-nodes-d540", "run:env2-fetchfirst-probe",
                   "run:env2-fetchfirst-probe-d540", "experiment/playbook-completion/findings/audit/zz-contract-2.json"]}

cells = {c["module"]: c for c in obl["cells"] if c.get("gate") == "3.2-coverage"}


def registered(r):
    f = PC / "evidence" / "runs" / f"{r}.json"
    return json.loads(f.read_text())["result"] if f.exists() else None


def module_summary(m):
    v = cov["modules"][m]
    fams = collections.Counter(r["family"] for r in v["features"] if r["status"] == "outside")
    resid = collections.Counter(r["residual"]["family"] for r in v["features"] if isinstance(r.get("residual"), dict))
    inside = sorted({c for r in v["features"] if r["status"] == "inside" for c in r["clauses"]})
    return v, fams, resid, inside


lines = [(HERE / "COVERAGE-2.head.md").read_text().rstrip(), "", "## Per module (generated by render.py from coverage.json)", ""]
lines.append("| Module | Features | Inside (r6 clauses) | Validated here | Outside (premise families, features) | Unclassified | Cell |")
lines.append("|---|---|---|---|---|---|---|")
for m in OPEN + CLOSED:
    v, fams, resid, inside = module_summary(m)
    c = v["counts"]
    fam_txt = ", ".join(f"{cov['families'][f]['premise'].split(':')[0]} {n}" for f, n in sorted(fams.items(), key=lambda x: -x[1]))
    lines.append(f"| {m} | {sum(c.values())} | {c['inside']} ({', '.join(inside)}) | {c['validated']} "
                 f"({', '.join(v['validated_clauses'])}) | {c['outside']}: {fam_txt} | {c['unclassified']} | {v['cell']} |")
lines += ["", "Module 00 owns no file in models/breadth-c/inventory.json (its terms are the product's shared vocabulary); "
          "its 3.2-coverage cell is already closed on env-ext-r6 and is not re-derived here.", "",
          "## Premise families (outside the contract: what stays assumed, and what depends on it)", "",
          "| Family | Premise | Consequence | Modules (features) |", "|---|---|---|---|"]
by_fam = collections.defaultdict(list)
for m in OPEN + CLOSED:
    v, fams, resid, inside = module_summary(m)
    for f, n in fams.items():
        by_fam[f].append(f"{m} ({n})")
    for f, n in resid.items():
        by_fam[f].append(f"{m} (residual of a validated clause: {n})")
for f, d in cov["families"].items():
    if f not in by_fam:
        continue
    lines.append(f"| {f} | {d['premise']} | {d['consequence']} | {', '.join(by_fam[f])} |")
(HERE / "COVERAGE-2.md").write_text("\n".join(lines) + "\n")

# ------------------------------------------------------------------------------------------------ MATRIX-INPUT
base_ev = ["run:env2-coverage-2", "run:env2-coverage-selftest", "run:env2-coverage-crosscheck", "run:env-ext-r6"]
out = {"lane": "contract-2", "pin": cov["pin"], "cells": []}
for m in OPEN + CLOSED:
    v, fams, resid, inside = module_summary(m)
    runs = []
    for cl in v["validated_clauses"]:
        for r in CLAUSE_RUNS.get(cl, []):
            if r not in runs:
                runs.append(r)
    old = cells.get(m, {})
    fails = list((old.get("product_basis") or {}).get("fails", []))
    undecided = list((old.get("product_basis") or {}).get("intent_undecided", []))
    for f in NEW_FINDINGS.get(m, []):
        fails.append(f"finding {f}")
    fails = list(dict.fromkeys(fails))
    findings = list(dict.fromkeys(x.replace("finding ", "") for x in fails))
    prem = sorted({cov["families"][f]["premise"].split(":")[0] for f in fams})
    status = "closed" if v["counts"]["unclassified"] == 0 else "open"
    cell = {
        "gate": "3.2-coverage", "module": m, "status": status,
        "evidence": base_ev + [f"run:{r}" for r in runs] + EXTRA_EV.get(m, []) + [
            f"experiment/playbook-completion/contract-2/coverage.json#modules.{m}",
            "experiment/playbook-completion/contract-2/COVERAGE-2.md"],
        "evidence_grade": "registered-run",
        "level": "method",
        "product_obligation": "fails" if fails else ("intent-undecided" if undecided else "unknown"),
        "product_basis": ("; ".join(fails + [f"intent-undecided {x}" for x in undecided])
                          or "no contract observation contradicts a product premise of this module; the outside "
                             "premises stay assumed (not shown to hold or fail)"),
        "as_built_findings": findings,
        "remaining": (f"gate met: {v['counts']['inside']} features inside r6 clauses, {v['counts']['validated']} "
                      f"validated by this lane ({', '.join(v['validated_clauses']) or 'none'}), {v['counts']['outside']} "
                      f"explicitly outside with premise and consequence (COVERAGE-2.md families); premises that stay "
                      f"assumed: {', '.join(prem)}"),
    }
    if m in CLOSED:
        cell["note"] = ("already closed (env-contract-r2); this lane's enumeration also classifies every feature; "
                        "proposed only to replace the evidence with the mechanical enumeration and to name the outside "
                        "premises the old cell did not list")
    if m == "17":
        cell["note"] = ("F-C1720 (new, S2): a contract observation (FETCH FIRST kills the client with the pin's locked "
                        "driver 5.3.2, env2-fetchfirst-probe) contradicts the premise at iris_sql_store.py:1177-1178; "
                        "reproduced through IRISGraphStore.query_nodes (env2-fc1720-query-nodes)")
    out["cells"].append(cell)
out["also"] = {
    "trust_premise_E-1": "TRUST.md row 'Embedded SQL (&sql) behaves as dynamic SQL for the clauses used' (status "
        "untested) -> validated for the pin's own compiled embedded statements: env2-e1-r1 (67 cases, 0 outside, 14/14 "
        "mutants) and env2-e1-r1-journal; S-1 (the pin's SQL functions Txn_Begin/End/Undo act on the caller's process "
        "and transaction) env2-e1-r2 (54 cases, 0 outside, 8/8 mutants). Residual: embedded forms not exercised "
        "(embedded UPDATE, cursors over many rows, %INLIST/%STARTSWITH/named %IGNOREINDEX in embedded text) by analogy.",
    "contract_r6_mutant_gap": "The r6 model applied the no-dirty-reads mutant to global reads only; no r6 mutant "
        "encoded READ COMMITTED for SQL SELECT. The contract-2 mutant sql-select-committed-only is killed by r6's own "
        "row-dirty-select observation (regress-r6.json), so E-VIS for SQL was decided by r6 data; the mutant list "
        "now encodes it.",
    "auditcore_residue": "After the E-1 rounds AUDITCORE holds 0 rows of the test prefix; the pin's AdjIndex left its "
        "non-transactional $Increment counters ^KG(\"gen\",\"env2e1g\",\"env2e1-r1\"|\"env2e1-r2\"), "
        "^KG(\"gen\",0,\"env2e1-n5\"|\"env2e1-n6\") and bumps of ^KG(\"__version\") (by design, Adjacency.cls:23-59); "
        "not removed (product-written globals; observation-only)",
}
(HERE / "MATRIX-INPUT.json").write_text(json.dumps(out, indent=1) + "\n")
print("wrote COVERAGE-2.md and MATRIX-INPUT.json:", len(out["cells"]), "cells")
