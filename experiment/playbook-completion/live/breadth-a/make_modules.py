    ws = writesets(results)
    out = ROOT / "modules"
    out.mkdir(exist_ok=True)
    for m in sorted(NAMES):
        doc = module_file(m, results, ws)
        (out / f"{m}.json").write_text(json.dumps(doc, indent=1) + "\n")
        st = {}
        for g in doc["gates_by_id"].values():
            st[g["status"]] = st.get(g["status"], 0) + 1
