def load(p):
    return json.loads(Path(p).read_text())


def store_match(w, reads):
    if w in reads:
        return True
    wr = w.split("(", 1)[0]
    return any(r.split("(", 1)[0] == wr and "(" not in r for r in reads) or \
        any(w.startswith(r.split("(", 1)[0]) and "(" not in w and r.startswith(w) for r in reads)


def writesets(results):
    passed = {c["family"] for c in results["checks"] if c["design"] == "reviewed" and c["kind"] == "safety"
              and c["result"] == "met"}
    out = {"_doc": "§3.3a write-set obligations for modules 01-06: every writer footprint (footprints/NN.json, role "
                   "writer/both) whose declared or journal-observed writes meet an invariant's read set. A pair is "
                   "'mc' when the invariant's explorer family models that writer (the reviewed design passes; the "
                   "as-built violation is the cited finding), 'finding' when only a finding covers it, else 'open'.",
           "invariants": {k: {"reads": v[0], "family": v[1], "findings": v[3]} for k, v in INVARIANTS.items()},
           "pairs": []}
    for m in sorted(NAMES):
        fp = load(ROOT / "footprints" / f"{m}.json")
        for e in fp["entry_points"]:
            if e.get("role") not in ("writer", "both"):
                continue
            writes = [w["store"].split(" [")[0] for w in e.get("writes", [])]
            for inv, (reads, fam, modeled, finds) in INVARIANTS.items():
                hit = sorted({w for w in writes if store_match(w, reads)})
                if not hit:
                    continue
                if any(s in e["id"] for s in modeled) and fam in passed:
                    status, by = "mc", f"mc:breadth-a-mc-{fam}-reviewed; finding:{','.join(finds)}"
                elif any(s in e["id"] for s in modeled):
                    status, by = "finding", ",".join(finds)
                else:
                    status, by = "open", ""
                out["pairs"].append({"invariant": inv, "module": m, "writer": e["id"], "writes": hit,
                                     "status": status, "discharged_by": by})
    cnt = {}
    for p in out["pairs"]:
        cnt.setdefault(p["module"], {}).setdefault(p["status"], 0)
        cnt[p["module"]][p["status"]] += 1
    out["counts_by_module"] = cnt
    (BA / "writesets.json").write_text(json.dumps(out, indent=1) + "\n")
    return out


def ontology_cells(m):
    path = next((REPO / "experiment/playbook-uplift/ontology").glob(f"{m}-*.md"))
    rows, on = [], False
    for ln in path.read_text().splitlines():
        if ln.startswith("## Cells"):
            on = True
            continue
        if on and ln.startswith("| ") and not ln.startswith("| Entity") and not ln.startswith("|---"):
            cols = [c.strip() for c in ln.strip("|").split("|")]
            if len(cols) >= 6:
                rows.append({"entity": cols[0], "state": cols[1], "command": cols[2], "outcome": cols[3],
                             "statements": cols[4], "decision": cols[5]})
    return rows, str(path.relative_to(REPO))


def G(status, evidence, remaining="", reason=""):
    d = {"status": status, "evidence": evidence}
    if remaining:
        d["remaining"] = remaining
    if reason:
        d["reason"] = reason
    return d


